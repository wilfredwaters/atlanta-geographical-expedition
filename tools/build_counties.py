"""Build counties.js: extra counties for the SVI map.

Inputs (download first, see README section in CLAUDE.md):
  SVI_2022_US.csv  https://svi.cdc.gov/Documents/Data/2022/csv/states/SVI_2022_US.csv
  tract GeoJSON per county, from Census cb_2022_<ST>_tract_500k (same
  source as the DeKalb shapes), e.g.
    ogr2ogr -f GeoJSON -lco COORDINATE_PRECISION=6 -t_srs EPSG:4326 \
      fulton.geojson cb_2022_13_tract_500k.shp -where "COUNTYFP='121'" \
      -select GEOID

Usage:
  python3 tools/build_counties.py SVI_2022_US.csv fulton.geojson wayne.geojson
  python3 tools/build_counties.py --check SVI_2022_US.csv   # vs DeKalb DATA

Output: counties.js with EXTRA_GEO (tract shapes + layer values) and
EXTRA_DATA (popup data, same shape as DATA in index.html).
"""

import csv
import json
import sys

MEASURES = ['POV150', 'UNEMP', 'HBURD', 'NOHSDP', 'UNINSUR', 'AGE65', 'AGE17',
            'DISABL', 'SNGPNT', 'LIMENG', 'MINRTY', 'MUNIT', 'MOBILE', 'CROWD',
            'NOVEH', 'GROUPQ']

# Conditions policy can change; Minority status counted at Wil's request.
STRUCTURAL = ['POV150', 'UNEMP', 'HBURD', 'NOHSDP', 'UNINSUR', 'LIMENG',
              'MINRTY', 'MUNIT', 'MOBILE', 'CROWD', 'NOVEH']

RATES = ['MINRTY', 'POV150', 'UNINSUR', 'HBURD']
QUARTER = 25.0
MISSING = -999.0
DEKALB = '13089'


def num(v):
    """CSV value as float, or None for CDC's -999 missing code."""
    x = float(v)
    if x == MISSING:
        return None
    return x


def entry(row):
    """Popup data for one tract: same fields as DATA in index.html."""
    d = {'n': row['LOCATION'].split(';')[0].strip()}
    rpl = num(row['RPL_THEMES'])

    # Rates first in dict order matters only for readability.
    rates = {}
    for m in RATES:
        v, moe = num(row['EP_' + m]), num(row['MP_' + m])
        rates[m] = None if v is None else [v, moe]

    if rpl is None:
        d.update(rates)
        return d

    # Each measure's share of the summed percentiles, in percent. Shares
    # are rounded as 4-decimal fractions first, as the DeKalb build did.
    epl = {m: float(row['EPL_' + m]) for m in MEASURES}
    total = sum(epl.values())
    sh = {m: round(epl[m] / total, 4) * 100 for m in MEASURES}
    ss = round(sum(epl[m] for m in STRUCTURAL) / total, 4) * 100
    order = sorted(MEASURES, key=lambda m: -epl[m])
    struct = [m for m in order if m in STRUCTURAL]

    # Fewest top measures that together reach a quarter of the score.
    q, cum = [], 0.0
    for m in order:
        q.append(m)
        cum += sh[m]
        if cum >= QUARTER:
            break

    d['r'] = round(rpl, 3)
    d['t'] = [[m, round(sh[m], 1)] for m in order[:5]]
    d['s'] = [[m, round(sh[m], 1)] for m in struct[:3]]
    d['s3'] = round(round(sum(epl[m] for m in struct[:3]) / total, 4) * 100, 1)
    d['ss'] = round(ss, 1)
    d['q'] = q
    d['sh'] = [round(sh[m], 2) for m in q]
    d.update(rates)
    return d


def read_svi(path):
    with open(path, encoding='utf-8-sig') as f:
        return {r['FIPS']: r for r in csv.DictReader(f)}


def check(svi):
    """Compare generated DeKalb entries with DATA in index.html."""
    html = open('index.html').read().split('\n')
    line = next(s for s in html if s.startswith('var DATA='))
    data = json.loads(line[len('var DATA='):].rstrip(';'))
    bad = [k for k, v in data.items() if entry(svi[k]) != v]
    print(len(data), 'tracts,', len(bad), 'differ', bad[:5])
    return not bad


def build(svi, shape_paths):
    feats, data = [], {}
    for p in shape_paths:
        for f in json.load(open(p))['features']:
            g = f['properties']['GEOID']
            row = svi[g]
            e = entry(row)
            data[g] = e
            props = {'GEOID': g,
                     'r': e.get('r'),
                     'd': e['s'][0][0] if 'r' in e else None,
                     'm': e['MINRTY'][0] if e['MINRTY'] else None}
            feats.append({'type': 'Feature', 'properties': props,
                          'geometry': f['geometry']})

    geo = {'type': 'FeatureCollection', 'features': feats}
    sep = (',', ':')
    with open('counties.js', 'w') as out:
        out.write('// Generated by tools/build_counties.py. Do not edit.\n')
        out.write('var EXTRA_GEO=' + json.dumps(geo, separators=sep) + ';\n')
        out.write('var EXTRA_DATA=' + json.dumps(data, separators=sep) + ';\n')
    print(len(feats), 'tracts written to counties.js')


def main(argv):
    if argv[0] == '--check':
        sys.exit(0 if check(read_svi(argv[1])) else 1)
    build(read_svi(argv[0]), argv[1:])


if __name__ == '__main__':
    main(sys.argv[1:])
